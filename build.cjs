/* Package each Garmin entry point with a private helper: no cross-file global dependency. */
const fs=require('node:fs'),path=require('node:path');
const dir=path.join(__dirname,'extension');
let helper=fs.readFileSync(path.join(dir,'garmin-archive.js'),'utf8').trim();
helper=helper.replace('globalThis.PPG_ARCHIVE={sanitize,archive,csv};','return {sanitize,archive,csv};');
if(!helper.includes('return {sanitize,archive,csv};'))throw Error('Archive helper export not found.');
helper=helper.replace(/;$/,'');
for(const name of ['garmin-capture','garmin-panel']){
 const source=fs.readFileSync(path.join(dir,name+'.js'),'utf8').replace('globalThis.PPG_ARCHIVE','privateArchive');
 const bundle='/* Generated by build.cjs — private archive helper + entry point. */\n(() => {\nconst privateArchive = '+helper+';\n'+source+'\n})();\n';
 fs.writeFileSync(path.join(dir,name+'.bundle.js'),bundle);
}
